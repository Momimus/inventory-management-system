<?php

namespace App\Enums\Concerns;

trait HasOptions
{
    /**
     * [value => label] pairs for select inputs.
     *
     * @return array<string, string>
     */
    public static function options(): array
    {
        return collect(self::cases())
            ->mapWithKeys(fn (self $case) => [$case->value => $case->label()])
            ->all();
    }
}
